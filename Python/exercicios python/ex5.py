'''Crie um programa que solicite três valores numéricos à
 pessoa usuária e imprima a soma dos três valores.'''

n1 = int(input("Digite o primeiro número:"))
n2 = int(input("Digite o segundo número:"))
n3 = int(input("Digite o segundo número:"))
soma = n1 + n2 + n3
print('a soma entre', n1, 'e', n2,'e', n3, 'é', soma)